import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const root = join(process.cwd(), 'artifacts', 'v22-browser');
const {samples} = JSON.parse(readFileSync(join(root, 'geometry.json'), 'utf8'));
const keys = ['heroButtons', 'routePanel', 'routeStops', 'hiker', 'stage', 'drawer'];
const rows = [];
for (const locale of ['uk', 'en']) {
  for (const width of [1440, 390]) {
    for (const name of ['hero', 'hoverla', 'brebeneskul', 'nesamovyte', 'petros']) {
      const original = samples.find(x => x.locale === locale && x.width === width && x.name === name && x.mode === 'original');
      const native = samples.find(x => x.locale === locale && x.width === width && x.name === name && x.mode === 'native');
      assert.ok(original && native, `missing measurement ${locale}/${width}/${name}`);
      for (const key of keys) {
        const left = original.elements[key] || [];
        const right = native.elements[key] || [];
        if (left.length !== right.length) {
          rows.push({locale, width, name, key, issue: 'count', original: left.length, native: right.length});
        }
        for (let i = 0; i < Math.min(left.length, right.length); i++) {
          const a = left[i].rect, b = right[i].rect;
          const delta = Object.fromEntries(['x', 'y', 'width', 'height'].map(k => [k, +(b[k] - a[k]).toFixed(2)]));
          const maxDelta = Math.max(...Object.values(delta).map(Math.abs));
          if (maxDelta > 1) rows.push({locale, width, name, key, index: i, text: left[i].text, delta, maxDelta});
        }
      }
    }
  }
}
rows.sort((a, b) => (b.maxDelta ?? Infinity) - (a.maxDelta ?? Infinity));
const report = {
  source: 'Original iframe vs native v22, matching viewport and scroll checkpoint',
  measurementPairs: 20,
  differencesAboveOnePixel: rows.length,
  differences: rows,
};
writeFileSync(join(root, 'geometry-diff.json'), JSON.stringify(report, null, 2));
const markdown = [
  '# v22 measured DOM geometry differences',
  '',
  'Generated by Chromium from original iframe and native port at matching scroll checkpoints.',
  'Values are native minus original, in CSS pixels. This is diagnostic, not a visual sign-off.',
  '',
  `Compared pairs: **20**. Differences over 1px: **${rows.length}**.`,
  '',
  '| Locale | Width | Scene | Element | Index | Δx | Δy | Δw | Δh |',
  '|---|---:|---|---|---:|---:|---:|---:|---:|',
  ...rows.slice(0, 100).map(x => `| ${x.locale} | ${x.width} | ${x.name} | ${x.key} | ${x.index ?? '-'} | ${x.delta?.x ?? '-'} | ${x.delta?.y ?? '-'} | ${x.delta?.width ?? '-'} | ${x.delta?.height ?? '-'} |`),
  '',
  'The complete untruncated results are in geometry-diff.json.',
  '',
].join('\n');
writeFileSync(join(root, 'geometry-diff.md'), markdown);
console.log(`Geometry comparison: ${rows.length} differences >1px across 20 scene pairs`);
